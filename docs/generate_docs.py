PROJECT_ROOT = SCRIPT_DIR.parent


@dataclass(frozen=True)
class DocsTarget:
    """One SDK to document: where to import from and where the pages go."""

    label: str
    import_root: Path
    output_dir: Path
    # module path -> page path without extension, relative to output_dir
    modules: dict[str, str]


