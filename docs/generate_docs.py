"""
Regenerate the reference docs for both Python SDKs.

Run with: uv run generate_docs.py

The rendering pipeline lives in sdk_docs_generate.py; this file only says what
to render: for each SDK, the input package root, the output docs folder, and
the module -> page mapping. Page paths mirror the autogenerated Docusaurus
sidebars, so a module's page path is its place in the sidebar. Docusaurus
ignores files starting with "_", which is why private modules such as
`_client` map to explicit page names.
"""

